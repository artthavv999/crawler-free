// Writes the Homebrew formula (Formula/crawler-free.rb) and the Scoop manifest (bucket/crawler-free.json) for a
// published standalone release (docs/beginner-cli-plan.md, E6). Run after publishing the GitHub release:
//   npm run cli:manifests            (the version in cli/package.json)
//   npm run cli:manifests -- 0.1.2   (another published version)
// Checksums come from the release's SHA256SUMS.txt and must match the digests GitHub reports for each file; nothing is
// typed by hand. Review the diff and commit it like any other change.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const REPO = "artthavv999/crawler-free";
const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const version = process.argv[2] ?? JSON.parse(await readFile(here("./package.json"), "utf8")).version;
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`"${version}" isn't a version number`);
const base = `https://github.com/${REPO}/releases/download/cli-v${version}`;

const sumsRes = await fetch(`${base}/SHA256SUMS.txt`);
if (!sumsRes.ok) throw new Error(`No SHA256SUMS.txt for cli-v${version} (HTTP ${sumsRes.status}); is the release published?`);
const sums = Object.fromEntries((await sumsRes.text()).trim().split("\n").map((line) => {
  const [hash, name] = line.trim().split(/\s+\*?/);
  return [name, hash];
}));
const release = await (await fetch(`https://api.github.com/repos/${REPO}/releases/tags/cli-v${version}`, { headers: { accept: "application/vnd.github+json" } })).json();
const digests = Object.fromEntries((release.assets ?? []).map((a) => [a.name, (a.digest ?? "").replace(/^sha256:/, "")]));

function asset(target, ext) {
  const name = `crawler-free-${version}-${target}.${ext}`;
  const sha256 = sums[name];
  if (!/^[0-9a-f]{64}$/.test(sha256 ?? "")) throw new Error(`${name} isn't listed in SHA256SUMS.txt`);
  if (digests[name] !== sha256) throw new Error(`${name}: SHA256SUMS.txt says ${sha256}, GitHub says ${digests[name] || "nothing"}`);
  return { url: `${base}/${name}`, sha256 };
}
const mac = { arm: asset("macos-arm64", "tar.gz"), intel: asset("macos-x64", "tar.gz") };
const linux = { arm: asset("linux-arm64", "tar.gz"), intel: asset("linux-x64", "tar.gz") };
const win = asset("windows-x64", "zip");

const formula = `# Generated by cli/manifests.mjs from the cli-v${version} release's SHA256SUMS.txt; don't edit by hand.
# Install: brew tap ${REPO} https://github.com/${REPO} && brew install crawler-free
class CrawlerFree < Formula
  desc "Read web pages as clean Markdown, links or facts with the free Crawler Free service"
  homepage "https://github.com/${REPO}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${mac.arm.url}"
      sha256 "${mac.arm.sha256}"
    end
    on_intel do
      url "${mac.intel.url}"
      sha256 "${mac.intel.sha256}"
    end
  end

  on_linux do
    on_arm do
      url "${linux.arm.url}"
      sha256 "${linux.arm.sha256}"
    end
    on_intel do
      url "${linux.intel.url}"
      sha256 "${linux.intel.sha256}"
    end
  end

  def install
    bin.install "crawler-free"
    prefix.install "LICENSE", "NODE-LICENSE.txt"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/crawler-free --version").strip
  end
end
`;

const scoop = {
  "##": `Generated by cli/manifests.mjs from the cli-v${version} release's SHA256SUMS.txt; don't edit by hand.`,
  version,
  description: "Read web pages as clean Markdown, links or facts with the free Crawler Free service.",
  homepage: `https://github.com/${REPO}`,
  license: "MIT",
  architecture: { "64bit": { url: win.url, hash: win.sha256 } },
  bin: "crawler-free.exe",
};

await mkdir(here("../Formula"), { recursive: true });
await mkdir(here("../bucket"), { recursive: true });
await writeFile(here("../Formula/crawler-free.rb"), formula);
await writeFile(here("../bucket/crawler-free.json"), `${JSON.stringify(scoop, null, 2)}\n`);
console.log(`wrote Formula/crawler-free.rb and bucket/crawler-free.json for ${version} (5 files, checksums match GitHub)`);
